public class bitwiseoperator {

    public static void main(String[] args) {
        
        int x = 5;
        int y = 7;

        System.out.println("x & y is: " + (x&y) );
        System.out.println("x | y is: " + (x|y));
        System.out.println("x ^ y is: " + (x^y));
        System.out.println("~x is: " + (~x));
      
    
}
}
