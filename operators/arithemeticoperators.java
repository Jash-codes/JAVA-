public class arithemeticoperators {

    public static void main(String[] args) {

        int a = 10;
        int b = 12;

        int add = a + b;
        int sub = b - a;
        int mul = a * b;
        int div = 12 / 10;
        int mod = 12 % 10;

        System.out.println("---ARITHMETIC OPERATORS---");
        System.out.println("the add of a and b is: " + add);
        System.out.println("the sub of a and b is: " + sub);
        System.out.println("the mul of a and b is: " + mul);
        System.out.println("the div of a and b is: " + div);
        System.out.println("the mod of a and b is: " + mod);
        System.out.println("-----------------------------");
        

    }
    
}
